"""The 13 benchmark tasks: loading config/tasks.yaml and generating it from the task files."""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .config import CONFIG_DIR, load_yaml
from .taskfile import parse_simple_yaml

# The website verifiers originally ran `npm install` before `node --test`. The image ships
# node_modules already installed, so that step is dropped (no network, no install memory spike).
_NPM_PREFIX = re.compile(r"^npm install --silent && ")


@dataclass(frozen=True)
class Task:
    id: str
    fixture: str          # directory name under the fixtures root
    prompt: str
    verify_cmd: str       # run with `sh -c` inside the work copy; exit 0 = pass
    timeout_s: int        # agent time limit
    tier: str = "T1"
    needs_node_modules: bool = False


def load_tasks(path: Path | None = None) -> list[Task]:
    data = load_yaml(path or CONFIG_DIR / "tasks.yaml")
    return [Task(**t) for t in data["tasks"]]


def get_task(tasks: list[Task], task_id: str) -> Task:
    for t in tasks:
        if t.id == task_id:
            return t
    raise KeyError(f"unknown task {task_id!r}; known: {[t.id for t in tasks]}")


def _verify_from_success(success: dict[str, Any], fixture: str) -> str:
    """Turn a task file's `success` block into one shell command run in the fixture root."""
    stype = success.get("type")
    if stype == "command":
        cmd = _NPM_PREFIX.sub("", str(success["command"]).strip())
        return cmd
    if stype == "file_contains":
        rel = Path(str(success["path"]))
        parts = rel.parts
        # paths are written as fixtures/<name>/<file>; the work copy IS the fixture root
        if len(parts) >= 3 and parts[0] == "fixtures":
            rel = Path(*parts[2:])
        pattern = str(success["pattern"]).replace("'", "'\"'\"'")
        return f"grep -qF -- '{pattern}' '{rel}'"
    raise ValueError(f"unsupported success type {stype!r}")


def generate_tasks(src_root: Path) -> list[dict[str, Any]]:
    """Read the 13 task files (tasks/suite.yaml order) and return tasks.yaml entries."""
    import yaml

    index = yaml.safe_load((src_root / "tasks" / "suite.yaml").read_text(encoding="utf-8"))
    entries: list[dict[str, Any]] = []
    for suite in index["suites"].values():
        for rel in suite["tasks"]:
            spec = parse_simple_yaml((src_root / "tasks" / rel).read_text(encoding="utf-8"))
            fixture = Path(spec["repo"]["path"]).name
            success = spec["success"]
            cmd = _verify_from_success(success, fixture)
            minutes = (spec.get("limits") or {}).get("timeout_minutes", 20)
            entries.append({
                "id": spec["id"],
                "fixture": fixture,
                "prompt": spec["prompt"].strip() + "\n",
                "verify_cmd": cmd,
                "timeout_s": int(minutes) * 60,
                "tier": "T1",
                "needs_node_modules": fixture == "dark-mode-site",
            })
    return entries


def write_tasks_yaml(entries: list[dict[str, Any]], path: Path | None = None) -> Path:
    import yaml

    path = path or CONFIG_DIR / "tasks.yaml"

    class _Dumper(yaml.SafeDumper):
        pass

    def _str(dumper: yaml.SafeDumper, value: str):
        style = "|" if "\n" in value else None
        return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)

    _Dumper.add_representer(str, _str)
    header = ("# Generated by `bench gen-tasks` from the 13 task files. Edit the task files, not this.\n"
              "# verify_cmd runs with `sh -c` in the work copy of the fixture; exit 0 = pass.\n")
    path.write_text(header + yaml.dump({"tasks": entries}, Dumper=_Dumper, sort_keys=False, width=100),
                    encoding="utf-8")
    return path
